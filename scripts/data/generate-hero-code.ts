/**
 * `pnpm data:hero-code` (ETE-90): the hero's code editor content, `profile.ts`, built from the data
 * files and highlighted here, at build time, so no highlighter ships to the browser. Writes
 * src/app/data/generated/hero-code.ts (committed). `--check` fails when the file is out of date
 * with the data: run `pnpm data:hero-code` after editing profile.json or skills.json.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { highlight } from '../../src/app/ui/molecules/code-block/highlight';

export const HERO_CODE_FILE = 'src/app/data/generated/hero-code.ts';
/** The categories whose newest featured skill goes in `stack`, in that order. */
const STACK_CATEGORIES = ['Frontend', 'Backend', 'Languages'] as const;

interface SkillLike {
  name: string;
  category: string;
  featured: boolean;
  since?: number;
}

/**
 * The profile object, as TypeScript: name, headline, base, the year the career started, and the
 * stack: the newest featured skill in Frontend, Backend and Languages (what is used today).
 */
export function heroCode(root: string): { code: string; highlightLines: number[] } {
  const read = (f: string) => JSON.parse(readFileSync(join(root, 'src/data', f), 'utf8'));
  const profile = read('profile.json');
  const skills: SkillLike[] = read('skills.json');
  const stack = STACK_CATEGORIES.map((category) =>
    skills
      .filter((s) => s.category === category && s.featured)
      .reduce<SkillLike | undefined>(
        (newest, s) => (!newest || (s.since ?? 0) > (newest.since ?? 0) ? s : newest),
        undefined,
      ),
  )
    .filter((s): s is SkillLike => !!s)
    .map((s) => JSON.stringify(s.name));
  const lines = [
    'const profile = {',
    `  name: ${JSON.stringify(profile.name)},`,
    `  role: ${JSON.stringify(profile.headline)},`,
    `  base: ${JSON.stringify(`${profile.location.city}, ${profile.location.country}`)},`,
    `  since: ${Number(profile.careerStart.slice(0, 4))},`,
    `  stack: [${stack.join(', ')}],`,
    '};',
  ];
  // The stack line is the one the editor highlights, as in the design.
  return {
    code: lines.join('\n'),
    highlightLines: [lines.findIndex((l) => l.includes('stack:')) + 1],
  };
}

/** The generated module's source. */
export function heroCodeModule(root: string): string {
  const { code, highlightLines } = heroCode(root);
  const file = { name: 'profile.ts', language: 'ts', lines: highlight(code, 'ts'), highlightLines };
  return [
    '/* Generated by scripts/data/generate-hero-code.ts from profile.json and skills.json. Do not edit. */',
    '/* Run `pnpm data:hero-code` after changing the data; `pnpm test:scripts` fails while it is stale. */',
    '',
    "/** The hero code editor's file, already highlighted (no highlighter in the browser). */",
    `export const heroCodeFile = ${JSON.stringify(file, null, 2)} as const;`,
    '',
  ].join('\n');
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const root = process.cwd();
  const source = heroCodeModule(root);
  if (process.argv.includes('--check')) {
    if (readFileSync(join(root, HERO_CODE_FILE), 'utf8') !== source) {
      console.error(`${HERO_CODE_FILE} is out of date: run pnpm data:hero-code`);
      process.exit(1);
    }
  } else {
    writeFileSync(join(root, HERO_CODE_FILE), source);
    console.log(`data:hero-code: wrote ${HERO_CODE_FILE}`);
  }
}
