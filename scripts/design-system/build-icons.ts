/**
 * `pnpm ds:icons` (ETE-69, ADR-004): the design system's icon set as one tree-shakable TypeScript
 * module, so each bundle carries only the icons its components import.
 *
 * - Source: src/styles/factman/icons.json, vendored from the Factman DS (`ICONS` in its
 *   components/bundle.js): `{ name: [pathData, strokeWidth] }`, or `[pathData, 0, 'fill']` for
 *   the filled brand marks.
 * - Output: src/app/ui/atoms/icon/icons.ts with one `IconDef` constant per icon
 *   (`arrow-right` → `iconArrowRight`) and the `IconName` union.
 *
 * `pnpm ds:icons --from <path/to/bundle.js>` refreshes icons.json from a new DS bundle first.
 * `pnpm ds:icons --check` fails when icons.ts is out of date with icons.json.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

export const ICONS_JSON = 'src/styles/factman/icons.json';
export const ICONS_TS = 'src/app/ui/atoms/icon/icons.ts';

/** `[pathData, strokeWidth]`, or `[pathData, 0, 'fill']` for filled marks. */
export type IconSource = [d: string, stroke: number, kind?: 'fill'];
export type IconSet = Record<string, IconSource>;

/** `arrow-up-right` → `iconArrowUpRight`; `2fa` → `icon2fa`. */
export const exportName = (name: string) =>
  'icon' +
  name
    .split('-')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');

/** The `ICONS` object literal from the DS components bundle. */
export function iconsFromBundle(bundle: string): IconSet {
  const line = bundle.split('\n').find((l) => /^\s*var ICONS = \{/.test(l));
  if (!line) throw new Error('no `var ICONS = {…}` line in the bundle');
  return JSON.parse(line.slice(line.indexOf('{'), line.lastIndexOf('}') + 1)) as IconSet;
}

export function readIcons(root: string): IconSet {
  return JSON.parse(readFileSync(join(root, ICONS_JSON), 'utf8')) as IconSet;
}

/** The generated module, Prettier-formatted. */
export async function renderIconsModule(icons: IconSet): Promise<string> {
  const names = Object.keys(icons).sort();
  const seen = new Map<string, string>();
  for (const n of names) {
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(n)) throw new Error(`icon name "${n}" is not kebab-case`);
    const id = exportName(n);
    if (seen.has(id)) throw new Error(`icons "${seen.get(id)}" and "${n}" both export ${id}`);
    seen.set(id, n);
  }
  const defs = names.map((n) => {
    const [d, stroke, kind] = icons[n];
    const shape = kind === 'fill' ? 'fill: true' : `stroke: ${stroke}`;
    return `export const ${exportName(n)}: IconDef = { name: '${n}', d: '${d}', ${shape} };`;
  });
  const source = [
    '// Generated by `pnpm ds:icons` from src/styles/factman/icons.json (ETE-69, ADR-004). Do not edit.',
    '// Import only the icons a component uses: unused ones are dropped from the bundle.',
    "import type { IconDef } from './icon-def';",
    '',
    `export type IconName = ${names.map((n) => `'${n}'`).join(' | ')};`,
    '',
    ...defs,
    '',
  ].join('\n');
  // The repo's own Prettier config, so lint-staged leaves the file unchanged.
  const options = await resolveConfig(ICONS_TS);
  return format(source, { ...options, filepath: ICONS_TS });
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = process.cwd();
  const run = async () => {
    const from = process.argv.indexOf('--from');
    if (from > 0) {
      const icons = iconsFromBundle(readFileSync(resolve(process.argv[from + 1]), 'utf8'));
      writeFileSync(join(root, ICONS_JSON), JSON.stringify(icons, null, 2) + '\n');
      console.log(`ds:icons: ${Object.keys(icons).length} icons written to ${ICONS_JSON}`);
    }
    const icons = readIcons(root);
    const next = await renderIconsModule(icons);
    const file = join(root, ICONS_TS);
    if (process.argv.includes('--check')) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== next) {
        console.error(`ds:icons: ${ICONS_TS} is out of date; run pnpm ds:icons`);
        process.exit(1);
      }
      console.log(`ds:icons: ${ICONS_TS} is up to date`);
      return;
    }
    writeFileSync(file, next);
    console.log(`ds:icons: ${Object.keys(icons).length} icons in ${ICONS_TS}`);
  };
  run().catch((e) => {
    console.error(`ds:icons failed: ${(e as Error).message}`);
    process.exit(1);
  });
}
