/**
 * `pnpm sync:github` (ETE-106, FR-33): reads the public contribution calendar of the GitHub
 * account in contact.json from GitHub's GraphQL API and writes it as a static snapshot to
 * src/app/data/generated/github-contributions.ts, so the site never calls GitHub from the browser.
 * Needs GITHUB_TOKEN (any token; the weekly workflow passes its own). The workflow commits the new
 * snapshot on a branch and opens a pull request; nothing is committed straight to a branch.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { ContributionSnapshot } from '../../src/app/shared/github/contributions';

export const SNAPSHOT_FILE = 'src/app/data/generated/github-contributions.ts';
const API = 'https://api.github.com/graphql';

/** The part of GitHub's GraphQL answer the snapshot needs. */
export interface CalendarResponse {
  data?: {
    user: {
      contributionsCollection: {
        contributionCalendar: {
          totalContributions: number;
          weeks: { contributionDays: { date: string; contributionCount: number }[] }[];
        };
      };
    } | null;
  };
  errors?: { message: string }[];
}

export const QUERY = `query($login: String!) {
  user(login: $login) {
    contributionsCollection {
      contributionCalendar {
        totalContributions
        weeks { contributionDays { date contributionCount } }
      }
    }
  }
}`;

/** The GitHub login from contact.json's `github` link (https://github.com/<login>). */
export function githubLogin(contact: { links: { id: string; url: string }[] }): string {
  const url = contact.links.find((l) => l.id === 'github')?.url;
  const login = url && new URL(url).pathname.split('/').filter(Boolean)[0];
  if (!login) throw new Error('contact.json has no github link to read the login from');
  return login;
}

/** GitHub's answer as a snapshot; throws with GitHub's message on an error or unknown user. */
export function toSnapshot(
  response: CalendarResponse,
  login: string,
  now: Date,
): ContributionSnapshot {
  if (response.errors?.length) throw new Error(response.errors.map((e) => e.message).join('; '));
  const calendar = response.data?.user?.contributionsCollection.contributionCalendar;
  if (!calendar) throw new Error(`GitHub has no user "${login}"`);
  const weeks = calendar.weeks.map((w) => w.contributionDays.map((d) => d.contributionCount));
  return {
    login,
    url: `https://github.com/${login}`,
    fetchedAt: now.toISOString(),
    start: calendar.weeks[0]?.contributionDays[0]?.date ?? now.toISOString().slice(0, 10),
    total: calendar.totalContributions,
    weeks,
  };
}

/** The generated module: the snapshot, or `null` when there is none (the graph then hides). */
export function renderModule(snapshot: ContributionSnapshot | null): string {
  return [
    '/* Generated by scripts/github/sync-github.ts (pnpm sync:github). Do not edit. */',
    '/* The weekly "Sync GitHub contributions" workflow refreshes it in a pull request. */',
    "import type { ContributionSnapshot } from '@shared';",
    '',
    '/** The GitHub contribution calendar (FR-33); null until the first sync. */',
    `export const githubContributions: ContributionSnapshot | null = ${JSON.stringify(snapshot)};`,
    '',
  ].join('\n');
}

async function main(): Promise<void> {
  const root = resolve(fileURLToPath(import.meta.url), '../../..');
  const token = process.env['GITHUB_TOKEN'];
  if (!token) throw new Error('GITHUB_TOKEN is not set: the GraphQL API needs a token');
  const contact = JSON.parse(readFileSync(join(root, 'src/data/contact.json'), 'utf8'));
  const login = githubLogin(contact);
  const res = await fetch(API, {
    method: 'POST',
    headers: { authorization: `bearer ${token}`, 'content-type': 'application/json' },
    body: JSON.stringify({ query: QUERY, variables: { login } }),
  });
  if (!res.ok) throw new Error(`GitHub answered ${res.status} ${res.statusText}`);
  const snapshot = toSnapshot((await res.json()) as CalendarResponse, login, new Date());
  writeFileSync(join(root, SNAPSHOT_FILE), renderModule(snapshot));
  console.log(
    `${SNAPSHOT_FILE}: ${snapshot.total} contributions by ${login} since ${snapshot.start}`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error: Error) => {
    console.error(`sync:github: ${error.message}`);
    process.exit(1);
  });
}
