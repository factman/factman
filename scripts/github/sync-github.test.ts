import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

import {
  type CalendarResponse,
  githubLogin,
  renderModule,
  SNAPSHOT_FILE,
  toSnapshot,
} from './sync-github';

const now = new Date('2026-11-24T06:00:00Z');
const day = (date: string, contributionCount: number) => ({ date, contributionCount });
const response: CalendarResponse = {
  data: {
    user: {
      contributionsCollection: {
        contributionCalendar: {
          totalContributions: 9,
          weeks: [
            { contributionDays: [day('2025-11-23', 0), day('2025-11-24', 4)] },
            { contributionDays: [day('2025-11-30', 5)] },
          ],
        },
      },
    },
  },
};

test("reads the login from contact.json's github link", () => {
  assert.equal(
    githubLogin({ links: [{ id: 'github', url: 'https://github.com/factman/' }] }),
    'factman',
  );
  assert.throws(() => githubLogin({ links: [] }), /no github link/);
});

test('keeps one count per day, by week, with the total and the first day', () => {
  assert.deepEqual(toSnapshot(response, 'factman', now), {
    login: 'factman',
    url: 'https://github.com/factman',
    fetchedAt: '2026-11-24T06:00:00.000Z',
    start: '2025-11-23',
    total: 9,
    weeks: [[0, 4], [5]],
  });
});

test("fails with GitHub's message, or when the user does not exist", () => {
  assert.throws(
    () => toSnapshot({ errors: [{ message: 'Bad credentials' }] }, 'x', now),
    /Bad credentials/,
  );
  assert.throws(() => toSnapshot({ data: { user: null } }, 'nobody', now), /no user "nobody"/);
});

test('writes a module the app imports, null before the first sync', () => {
  const module = renderModule(toSnapshot(response, 'factman', now));
  assert.match(module, /^\/\* Generated by scripts\/github\/sync-github\.ts/);
  assert.match(
    module,
    /export const githubContributions: ContributionSnapshot \| null = \{"login":"factman"/,
  );
  assert.match(renderModule(null), /= null;/);
  // The committed file is one this script wrote.
  assert.match(
    readFileSync(SNAPSHOT_FILE, 'utf8'),
    /Generated by scripts\/github\/sync-github\.ts/,
  );
});
